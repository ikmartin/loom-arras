// The proposed results queue in Review › Library (WQ-55): every waiting proposal in the library, grouped by work, one at a time at full width, the paper's words above and the rendering beneath, the words the page does not have marked, the verbs under it with keys. The states are the design study's. Verifying, editing and discarding against a real publisher are in the write suite.
import { expect, test, type Page } from '@playwright/test';
import { serve } from '../manifest';
import { prefs } from '../workspace';

type M = Parameters<Parameters<typeof serve>[1]>[0];

/** A proposal of `ck` as the publisher writes one; `over` changes any field. */
function propose(m: M, ck: string, id: string, over: Record<string, unknown> = {}): void {
	const r = m.references[ck];
	r.results = { ...(r.results ?? {}) };
	r.results[id] = {
		state: 'proposed',
		level: 1,
		class: 'anchored',
		page: 1,
		artifact: 'df039aa2ab80',
		origin: [{ act: 'proposed', by: 'run:2026-09-18T20-00', when: '2026-09-18T20:00:00Z' }],
		source_text: 'Every cycle group is generated by integral cycles.',
		statement: 'Every cycle group is generated by integral cycles.',
		page_text: 'Theorem 9.9. Every cycle group is generated by integral cycles.',
		...over
	};
	r.proposed = { file: `digests/${ck}.proposed.tex`, fragment: '', nodes: [...(r.proposed?.nodes ?? []), id] };
}

/** A three-page PDF, so a proposal past page one has a page to be drawn on. */
const PDF3 = `%PDF-1.4
1 0 obj<</Type/Catalog/Pages 2 0 R>>endobj
2 0 obj<</Type/Pages/Kids[3 0 R 4 0 R 5 0 R]/Count 3>>endobj
3 0 obj<</Type/Page/Parent 2 0 R/MediaBox[0 0 612 792]>>endobj
4 0 obj<</Type/Page/Parent 2 0 R/MediaBox[0 0 612 792]>>endobj
5 0 obj<</Type/Page/Parent 2 0 R/MediaBox[0 0 612 792]>>endobj
trailer<</Root 1 0 R>>
%%EOF`;

async function paper(page: Page, quads: Record<string, number[][]>): Promise<void> {
	await page.route('**/paper.pdf', (route) => route.fulfill({ body: PDF3, contentType: 'application/pdf' }));
	await page.route('**/spans/**.json', (route) => route.fulfill({ json: { artifact: 'df039aa2ab80', pages: {}, quads } }));
}

const card = (page: Page) => page.getByTestId('proposal');

test('one queue holds every waiting proposal, grouped by work, a result at a time, moved through by key', async ({ page }) => {
	await serve(page, (m) => {
		propose(m, 'Kre99', 'Kre99-thm-9.9');
		propose(m, 'Kre99', 'Kre99-thm-9.10', { page: 2 });
		propose(m, 'Har77', 'Har77-prop-1.1');
		propose(m, 'Man12', 'Man12-def-2.3');
	});
	await page.goto('/review/library');
	const queue = page.getByTestId('proposal-queue');
	await expect(queue.locator('h2')).toContainText('Proposed results 4');
	await expect(page.getByTestId('queue-works').getByRole('button')).toHaveText([/Hartshorne, Algebraic Geometry 1/, /Kresch, Cycle groups for Artin stacks 2/, /Manolache, Virtual pull-backs 1/]);
	await expect(card(page)).toHaveCount(1);
	await expect(page.getByTestId('queue-at')).toHaveText('1 of 4');
	await queue.focus();
	await page.keyboard.press('ArrowDown');
	await expect(page.getByTestId('queue-at')).toHaveText('2 of 4');
	await page.keyboard.press('ArrowUp');
	await page.keyboard.press('ArrowUp');
	await expect(page.getByTestId('queue-at')).toHaveText('4 of 4');
	await page.getByTestId('queue-work-Kre99').click();
	await expect(card(page)).toHaveAttribute('data-id', 'Kre99-thm-9.9');
	// Review counts them in the column
	await expect(page.getByTestId('section-library')).toHaveAttribute('title', /4 proposed results/);
});

test('a card names the result as the paper does, and folds the id and the hash', async ({ page }) => {
	await serve(page, (m) => {
		propose(m, 'Kre99', 'Kre99-thm-9.9', { page: 12 });
		m.nodes['Kre99-thm-9.9'] = { ...structuredClone(m.nodes['Kre99-thm-2.1']), id: 'Kre99-thm-9.9', locator: 'Theorem 9.9, p.~12', fragment: '' };
	});
	await page.goto('/review/library');
	await expect(page.getByTestId('proposal-name')).toHaveText('Theorem 9.9 · Kresch, Cycle groups for Artin stacks, p. 12');
	const facts = card(page).locator('details.facts');
	await expect(facts).not.toHaveAttribute('open');
	await facts.locator('summary').click();
	await expect(facts).toContainText('Kre99-thm-9.9');
	await expect(facts).toContainText('df039aa2ab80');
	await expect(facts).toContainText('run:2026-09-18T20-00');
});

test('the paper\'s words above, cropped to the statement at the card\'s width; the rendering beneath with the words the page lacks marked', async ({ page }) => {
	await paper(page, { 'Kre99-thm-9.9': [[72, 100, 400, 116]] });
	await page.route('**/fragments/nodes/Kre99-thm-9.9.html', (route) =>
		route.fulfill({ contentType: 'text/html', body: '<div class="env env-theorem" data-key="Kre99-thm-9.9" data-id="Kre99-thm-9.9"><p>Every cycle group (in the sense of Deligne and Mumford) is generated by integral cycles.</p></div>' })
	);
	await serve(page, (m) => {
		const r = m.references.Kre99;
		r.artifacts.pdf = true;
		r.spans = { path: 'spans/arxiv/math_9810166v2.json', sha256: 'abc' };
		propose(m, 'Kre99', 'Kre99-thm-9.9', {
			statement: 'Every cycle group (in the sense of Deligne and Mumford) is generated by integral cycles.',
			not_on_page: ['sense', 'Deligne', 'Mumford']
		});
		m.nodes['Kre99-thm-9.9'] = { ...structuredClone(m.nodes['Kre99-thm-2.1']), id: 'Kre99-thm-9.9', locator: 'Theorem 9.9, p.~1', fragment: 'fragments/nodes/Kre99-thm-9.9.html' };
	});
	await page.setViewportSize({ width: 1440, height: 900 });
	await page.goto('/review/library');
	const crop = page.getByTestId('proposal-paper');
	await expect(crop.getByTestId('pdf-page-1')).toBeVisible();
	await expect(page.getByTestId('mark-Kre99-thm-9.9').first()).toBeVisible();
	// the page is the card's width, and the window is the statement's height and a little, not the page's
	const box = (await crop.boundingBox())!;
	const width = (await card(page).boundingBox())!.width;
	expect(box.width).toBeGreaterThan(width * 0.9);
	expect(box.height).toBeLessThan(box.width * (792 / 612) * 0.5);
	// the rendering is the publisher's, beneath at the same width, its words the page lacks marked as compare marks a changed word
	const rendering = page.getByTestId('proposal-statement');
	await expect(rendering.locator('mark.review-changed')).toHaveText(['sense', 'Deligne', 'Mumford']);
	await expect(page.getByTestId('proposal-added')).toHaveText('3 words not found on the page');
	expect(Math.abs((await rendering.boundingBox())!.width - box.width)).toBeLessThan(40);
});

