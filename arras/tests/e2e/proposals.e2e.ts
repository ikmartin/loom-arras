for (const [width, name] of [
	[1440, 'a full pane'],
	[900, 'half the window'],
	[400, 'a phone']
] as const) {
	test(`at ${name} the card fits, its verbs and both texts within the window`, async ({ page }) => {
		await serve(page, (m) => propose(m, 'Kre99', 'Kre99-thm-9.9'));
		await page.setViewportSize({ width, height: 900 });
		await page.goto('/review/library');
		await expect(card(page)).toBeVisible();
		const whole = (await card(page).boundingBox())!;
		expect(whole.x + whole.width).toBeLessThanOrEqual(width + 1);
		// both texts, and the footer the verbs stand in where a publisher serves them
		for (const part of [page.getByTestId('proposal-source'), page.getByTestId('proposal-statement'), card(page).locator('footer')]) {
			const box = (await part.boundingBox())!;
			expect(box.x + box.width).toBeLessThanOrEqual(width + 1);
		}
	});
}

