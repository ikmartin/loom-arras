test('a proposal past the first page is drawn on its own page, after another before it', async ({ page }) => {
	// the second card's page measured against the pane rather than its column was drawn blank: the wrong page was followed
	await paper(page, { 'Kre99-thm-9.9': [[72, 100, 400, 116]], 'Kre99-thm-9.10': [[72, 300, 400, 316]] });
	await serve(page, (m) => {
		const r = m.references.Kre99;
		r.artifacts.pdf = true;
		r.spans = { path: 'spans/arxiv/math_9810166v2.json', sha256: 'abc' };
		propose(m, 'Kre99', 'Kre99-thm-9.9');
		propose(m, 'Kre99', 'Kre99-thm-9.10', { page: 3 });
	});
	await page.goto('/review/library');
	await expect(page.getByTestId('proposal-paper').getByTestId('pdf-page-1').locator('canvas')).toBeAttached();
	await page.getByTestId('queue-next').click();
	await expect(card(page)).toHaveAttribute('data-id', 'Kre99-thm-9.10');
	await expect(page.getByTestId('proposal-paper').getByTestId('pdf-page-3').locator('canvas')).toBeAttached();
});

test('ten proposals are gone through by key alone, the queue wrapping at its end', async ({ page }) => {
	await serve(page, (m) => {
		for (let i = 1; i <= 10; i++) propose(m, 'Kre99', `Kre99-thm-9.${i}`, { page: i });
	});
	await page.goto('/review/library');
	await page.getByTestId('proposal-queue').focus();
	for (let i = 2; i <= 10; i++) {
		await page.keyboard.press('ArrowDown');
		await expect(page.getByTestId('queue-at')).toHaveText(`${i} of 10`);
	}
	await page.keyboard.press('ArrowDown');
	await expect(page.getByTestId('queue-at')).toHaveText('1 of 10');
});

